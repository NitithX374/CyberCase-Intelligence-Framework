"""Cross-check every cited bibliography entry against an authoritative record.

DOI entries -> Crossref; arXiv entries -> arXiv API, plus Semantic Scholar for a later published
venue; other entries are listed for a manual check. Compares title (normalised similarity), first
author surname and year, and writes a Markdown report.

Run from paper/ubimedia2027:  python3 tools/crosscheck_citations.py > citation_crosscheck.md
"""
import difflib
import json
import re
import sys
import time
import urllib.request
import xml.etree.ElementTree as ET

UA = {"User-Agent": "citation-crosscheck/1.0 (mailto:s6604062630021@kmutnb.ac.th)"}


def get(url, tries=4):
    for i in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code in (429, 503) and i < tries - 1:
                time.sleep(5 * (i + 1))
                continue
            raise
    return b""


def norm(t):
    t = re.sub(r"\\[a-zA-Z]+|[{}\\]", "", t or "")
    return re.sub(r"[^a-z0-9]+", " ", t.lower()).strip()


def field(body, name):
    m = re.search(name + r"\s*=\s*[{\"](.+?)[}\"]\s*,?\s*\n", body, flags=re.S)
    return " ".join(m.group(1).split()) if m else ""


def first_surname(authors):
    a = authors.split(" and ")[0].strip()
    return norm(a.split(",")[0] if "," in a else a.split()[-1]).split()[-1] if a else ""


bib = open("references.bib").read()
tex = open("main.tex").read()
cited = {k.strip() for c in re.findall(r"\\cite\{([^}]*)\}", tex) for k in c.split(",")}
entries = [(t, k, b + "\n") for t, k, b in re.findall(r"@(\w+)\{([^,]+),(.*?)\n\}", bib, flags=re.S) if k in cited]

rows = []
for typ, key, body in entries:
    title, year, authors = field(body, "title"), field(body, "year"), field(body, "author")
    doi, eprint = field(body, "doi"), field(body, "eprint")
    rec = {"key": key, "src": "", "title_sim": None, "author_ok": None, "year": "", "venue": "", "note": ""}
    try:
        if doi:
            d = json.loads(get("https://api.crossref.org/works/" + urllib.request.quote(doi)))["message"]
            rt = (d.get("title") or [""])[0]
            fam = norm((d.get("author") or [{}])[0].get("family", ""))
            parts = (d.get("published-print") or d.get("published-online") or d.get("issued") or {}).get("date-parts", [[None]])[0]
            rec.update(src="Crossref " + doi, title_sim=difflib.SequenceMatcher(None, norm(title), norm(rt)).ratio(),
                       author_ok=(fam.split()[-1] if fam else "") == first_surname(authors) if fam else None,
                       year=f"{year} vs {parts[0]}", venue=((d.get("container-title") or [""])[0])[:70])
            time.sleep(0.3)
        elif eprint:
            x = get(f"https://export.arxiv.org/api/query?id_list={eprint}")
            ns = {"a": "http://www.w3.org/2005/Atom", "x": "http://arxiv.org/schemas/atom"}
            e = ET.fromstring(x).find("a:entry", ns)
            rt = " ".join(e.find("a:title", ns).text.split())
            fa = norm(e.find("a:author/a:name", ns).text).split()[-1]
            ry = e.find("a:published", ns).text[:4]
            com = e.find("x:comment", ns)
            rec.update(src="arXiv " + eprint, title_sim=difflib.SequenceMatcher(None, norm(title), norm(rt)).ratio(),
                       author_ok=fa == first_surname(authors), year=f"{year} vs {ry} (arXiv v1)",
                       note=("arXiv comment: " + " ".join(com.text.split())[:60]) if com is not None else "")
            time.sleep(3)
            s = json.loads(get(f"https://api.semanticscholar.org/graph/v1/paper/arXiv:{eprint}?fields=venue,publicationVenue,year"))
            pv = (s.get("publicationVenue") or {}).get("name") or s.get("venue") or ""
            rec["venue"] = ("published: " + pv) if pv and "arxiv" not in pv.lower() else "preprint (no venue in Semantic Scholar)"
            time.sleep(3)
        else:
            rec.update(src="manual", note=field(body, "url") or field(body, "note") or field(body, "howpublished"))
    except Exception as ex:  # noqa: BLE001
        rec["note"] = f"lookup failed: {ex}"
    rows.append(rec)

print("# Citation cross-check\n")
print(f"{len(rows)} cited entries; generated by tools/crosscheck_citations.py.\n")
print("| Key | Source | Title match | First author | Year (bib vs record) | Venue / status | Note |")
print("|---|---|---|---|---|---|---|")
for r in rows:
    ts = "" if r["title_sim"] is None else f"{r['title_sim']:.2f}"
    au = "" if r["author_ok"] is None else ("ok" if r["author_ok"] else "MISMATCH")
    print(f"| {r['key']} | {r['src']} | {ts} | {au} | {r['year']} | {r['venue']} | {r['note']} |")
